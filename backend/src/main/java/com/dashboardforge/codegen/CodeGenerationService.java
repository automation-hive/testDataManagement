package com.dashboardforge.codegen;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.Set;
import java.util.regex.Pattern;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

@Service
public class CodeGenerationService {
    private static final Set<String> COMPONENT_TYPES = Set.of(
        "BUTTON", "TEXT_FIELD", "DROPDOWN", "CHECKBOX", "METRIC_CARD",
        "DATA_TABLE", "CHART", "ALERT", "STATUS_BADGE"
    );
    private static final Pattern SAFE_NAME = Pattern.compile("[^a-zA-Z0-9_-]+");
    private final ObjectMapper mapper;

    public CodeGenerationService(ObjectMapper mapper) {
        this.mapper = mapper;
    }

    public String fileName(String projectName) {
        String safe = SAFE_NAME.matcher(projectName == null ? "" : projectName.trim())
            .replaceAll("-").replaceAll("^-+|-+$", "");
        return safe.isBlank() ? "dashboard" : safe.toLowerCase();
    }

    public byte[] generate(CodeGenerationRequest request) {
        JsonNode config;
        try {
            config = mapper.readTree(request.configJson());
        } catch (IOException exception) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Dashboard configuration must be valid JSON.");
        }
        JsonNode components = config.path("components");
        if (!components.isArray() || components.size() > 100) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST,
                "Configuration must contain a components array with no more than 100 entries.");
        }
        for (JsonNode component : components) {
            String type = component.path("type").asText("");
            if (!COMPONENT_TYPES.contains(type)) {
                throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Unsupported dashboard component type: " + type);
            }
            if (!component.path("properties").isObject()) {
                throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Each component must contain a properties object.");
            }
        }

        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            try (ZipOutputStream zip = new ZipOutputStream(bytes, StandardCharsets.UTF_8)) {
                add(zip, "react/src/generated/DashboardView.tsx", reactView(config, request.projectName()));
                add(zip, "react/README.md", reactReadme());
                add(zip, "java/src/main/java/generated/dashboard/DashboardActionRequest.java", javaRequest());
                add(zip, "java/src/main/java/generated/dashboard/DashboardActionController.java", javaController());
                add(zip, "java/README.md", javaReadme());
                add(zip, "dashboard.config.json", mapper.writerWithDefaultPrettyPrinter().writeValueAsString(config));
                add(zip, "GENERATION-NOTES.md", notes(request.projectName()));
            }
            return bytes.toByteArray();
        } catch (IOException exception) {
            throw new ResponseStatusException(HttpStatus.INTERNAL_SERVER_ERROR, "Could not generate source archive.");
        }
    }

    private String reactView(JsonNode config, String projectName) throws IOException {
        String serialized = mapper.writerWithDefaultPrettyPrinter().writeValueAsString(config);
        String titleLiteral = mapper.writeValueAsString(projectName);
        return """
            import React from 'react';

            // Generated by DashboardForge. Customize this view in your application.
            export const dashboardConfig = %s as const;
            const dashboardTitle = %s;

            type ComponentConfig = {
              id: string;
              type: string;
              label: string;
              actionKey?: string;
              properties: Record<string, string | number | boolean>;
            };

            function renderComponent(component: ComponentConfig) {
              const props = component.properties;
              switch (component.type) {
                case 'BUTTON':
                  return <button disabled={Boolean(props.disabled)}>{component.label}</button>;
                case 'TEXT_FIELD':
                  return <label>{component.label}<input placeholder={String(props.placeholder ?? '')} maxLength={Number(props.maxLength ?? 100)} /></label>;
                case 'DROPDOWN':
                  return <label>{component.label}<select defaultValue=""><option value="">{String(props.placeholder ?? 'Select')}</option>{String(props.options ?? '').split(',').map((option) => option.trim()).filter(Boolean).map((option) => <option key={option}>{option}</option>)}</select></label>;
                case 'CHECKBOX':
                  return <label><input type="checkbox" defaultChecked={Boolean(props.checked)} />{String(props.text ?? component.label)}</label>;
                case 'METRIC_CARD':
                  return <article><h3>{component.label}</h3><strong>{String(props.value ?? '')}</strong><p>{String(props.caption ?? '')} {String(props.trend ?? '')}</p></article>;
                case 'DATA_TABLE':
                  return <article><h3>{component.label}</h3><p>Configure a data source to populate this table.</p></article>;
                case 'CHART':
                  return <article><h3>{String(props.title ?? component.label)}</h3><p>Connect a data source to render this chart.</p></article>;
                case 'ALERT':
                  return <aside role="status">{String(props.message ?? component.label)}</aside>;
                case 'STATUS_BADGE':
                  return <span>{String(props.text ?? component.label)}</span>;
                default:
                  return null;
              }
            }

            export default function DashboardView() {
              return (
                <main className="dashboard-forge-view">
                  <h1>{dashboardTitle}</h1>
                  <section className="dashboard-forge-grid">
                    {dashboardConfig.components.map((component) => (
                      <div key={component.id} className="dashboard-forge-component">
                        {renderComponent(component)}
                      </div>
                    ))}
                  </section>
                </main>
              );
            }
            """.formatted(serialized, titleLiteral);
    }

    private static String javaRequest() {
        return """
            package generated.dashboard;

            import jakarta.validation.constraints.NotBlank;
            import java.util.Map;

            public record DashboardActionRequest(
                @NotBlank String actionKey,
                Map<String, Object> inputs
            ) {}
            """;
    }

    private static String javaController() {
        return """
            package generated.dashboard;

            import com.dashboardforge.action.ActionRegistry;
            import org.springframework.http.HttpStatus;
            import org.springframework.web.bind.annotation.*;
            import org.springframework.web.server.ResponseStatusException;

            @RestController
            @RequestMapping("/api/generated-dashboard/actions")
            public class DashboardActionController {
                private final ActionRegistry actionRegistry;

                public DashboardActionController(ActionRegistry actionRegistry) {
                    this.actionRegistry = actionRegistry;
                }

                @PostMapping("/execute")
                public Object execute(@RequestBody DashboardActionRequest request) {
                    try {
                        return actionRegistry.execute(request.actionKey(),
                            request.inputs() == null ? java.util.Map.of() : request.inputs());
                    } catch (java.util.NoSuchElementException exception) {
                        throw new ResponseStatusException(HttpStatus.NOT_FOUND, "Action is not registered.");
                    } catch (IllegalArgumentException exception) {
                        throw new ResponseStatusException(HttpStatus.BAD_REQUEST, exception.getMessage());
                    }
                }
            }
            """;
    }

    private static String reactReadme() {
        return """
            # Generated React view

            Copy the generated DashboardView.tsx into a React + TypeScript application.
            It requires React and uses the dashboard configuration embedded in the file.
            The data table and chart are structural placeholders; connect them to your own data source.
            Action keys are metadata only. Wire buttons to authenticated application services explicitly.
            """;
    }

    private static String javaReadme() {
        return """
            # Generated Java integration scaffold

            Copy the generated Java files into a Spring Boot project that already includes
            the DashboardForge ActionRegistry (or adapt the import to your own allowlisted registry).
            The controller delegates only to registered action keys. It does not execute arbitrary
            class names, methods, source code, or shell commands.
            Add authentication, authorization, rate limits, and audit logging before production use.
            """;
    }

    private static String notes(String projectName) {
        return """
            # DashboardForge source export

            Project: %s

            This archive contains:
            - A React + TypeScript dashboard view.
            - The dashboard configuration as JSON.
            - A Java Spring Boot action-controller scaffold that delegates to the allowlisted ActionRegistry.

            Generated files are starter code. Review, test, and adapt them before deploying.
            """.formatted(projectName.replace("\r", " ").replace("\n", " "));
    }

    private static void add(ZipOutputStream zip, String path, String content) throws IOException {
        zip.putNextEntry(new ZipEntry(path));
        zip.write(content.getBytes(StandardCharsets.UTF_8));
        zip.closeEntry();
    }
}
